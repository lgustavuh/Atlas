-- Função imutável para busca sem acento (usada em índices).
create or replace function public.sem_acento(text) returns text
language sql immutable parallel safe as $$ select lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce($1, ''))) $$;

create or replace function public.tg_atualizado_em() returns trigger
language plpgsql as $$ begin new.atualizado_em := now(); return new; end $$;

