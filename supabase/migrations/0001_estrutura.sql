create or replace function public.tg_auditar() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_antes jsonb := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end;
  v_depois jsonb := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end;
begin
  if tg_op = 'UPDATE' and v_antes = v_depois then
    return new;
  end if;
  insert into auditoria (usuario_id, tabela, operacao, registro_id, antes, depois)
  values (auth.uid(), tg_table_name, tg_op,
          coalesce(v_depois ->> 'id', v_antes ->> 'id'), v_antes, v_depois);
  return coalesce(new, old);
end $$;

