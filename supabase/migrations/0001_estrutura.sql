-- Nível por módulo (herdado do sistema antigo):
-- 2 = visualizar · 3 = alterar · 4 = cadastrar · 5 = excluir/desativar · 6 = ações especiais
create table public.permissoes (
  usuario_id uuid not null references public.usuarios (id) on delete cascade,
  modulo text not null references public.modulos (codigo) on delete cascade,
  nivel smallint not null check (nivel between 0 and 6),
  primary key (usuario_id, modulo)
);

create or replace function public.eh_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from usuarios where id = auth.uid() and ativo and admin)
$$;

create or replace function public.tem_nivel(p_modulo text, p_nivel int) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from usuarios where id = auth.uid() and ativo and admin)
      or exists (
        select 1 from permissoes p join usuarios u on u.id = p.usuario_id
        where p.usuario_id = auth.uid() and u.ativo and p.modulo = p_modulo and p.nivel >= p_nivel)
$$;

create or replace function public.tem_nivel_algum(p_modulos text[], p_nivel int) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from usuarios where id = auth.uid() and ativo and admin)
      or exists (
        select 1 from permissoes p join usuarios u on u.id = p.usuario_id
        where p.usuario_id = auth.uid() and u.ativo and p.modulo = any (p_modulos) and p.nivel >= p_nivel)
$$;

