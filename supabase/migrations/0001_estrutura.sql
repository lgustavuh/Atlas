-- Novo registro ativo de segurança/classificação vira o atual; o anterior passa a histórico.
create or replace function public.tg_versionar_por_colaborador() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'ativo' then
    execute format('update public.%I set status = ''historico''
                    where colaborador_id = $1 and status = ''ativo'' and id <> $2', tg_table_name)
      using new.colaborador_id, new.id;
  end if;
  return new;
end $$;

create trigger versionar after insert on public.seguranca
  for each row execute function public.tg_versionar_por_colaborador();
create trigger versionar after insert on public.classificacoes
  for each row execute function public.tg_versionar_por_colaborador();

-- Vencimento de NR calculado pela validade cadastrada; o anterior da mesma NR vira histórico.
create or replace function public.tg_treinamento_nr() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.data_vencimento is null then
    select new.data_realizacao + validade_dias into new.data_vencimento from public.nrs where codigo = new.nr;
  end if;
  if tg_op = 'INSERT' and new.status = 'ativo' then
    update public.treinamentos_nr set status = 'historico'
     where colaborador_id = new.colaborador_id and nr = new.nr and status = 'ativo';
  end if;
  return new;
end $$;

create trigger calcular before insert or update of data_realizacao, nr on public.treinamentos_nr
  for each row execute function public.tg_treinamento_nr();

-- Mudança de status (desativar/reativar) exige nível 5 no módulo.
create or replace function public.tg_exigir_nivel_status() returns trigger
language plpgsql as $$
begin
  if new.status is distinct from old.status
     and current_user not in ('postgres', 'service_role', 'supabase_admin')
     and not public.tem_nivel(tg_argv[0], 5) then
    raise exception 'Sem permissão para alterar a situação deste registro (nível 5 em %).', tg_argv[0]
      using errcode = '42501';
  end if;
  return new;
end $$;

-- ---------------------------------------------------------------------
-- Usuário criado no Auth → linha em usuarios (o primeiro vira administrador)
-- ---------------------------------------------------------------------
create or replace function public.tg_novo_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into usuarios (id, nome, email, admin)
  values (new.id,
          coalesce(new.raw_user_meta_data ->> 'nome', split_part(new.email, '@', 1)),
          new.email,
          not exists (select 1 from usuarios));
  return new;
end $$;

create trigger ao_criar_usuario after insert on auth.users
  for each row execute function public.tg_novo_usuario();
